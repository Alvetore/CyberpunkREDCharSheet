"""Import ammo/ ammo-77 from a saved Data Pool weapons page (stdlib only).

python scripts/import-ammunition.py [--source PATH] [--check]
Catalog quantities count packs; rockets count individual rounds. Grenades use
the existing weapon catalog. Source effects remain descriptive, never executed.
"""
import argparse
from hashlib import sha256
import json
from pathlib import Path
import re
import unicodedata
from datapool_tables import Tables

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'audit/source/ammo-current.html'
OUTPUT = ROOT / 'src/data/ammunitionCatalog.ts'
# Calibers are separate purchases, even when their package prices coincide.
TYPES = [
    ('medium', 'Патроны среднего пистолета / ПП', 'bullets'),
    ('heavy', 'Патроны тяжёлого пистолета / тяжёлого ПП', 'bullets'),
    ('very-heavy', 'Патроны очень тяжёлого пистолета', 'bullets'),
    ('rifle', 'Винтовочные патроны', 'bullets'),
    ('slugs', 'Жаканы для дробовика', 'slugs'),
    ('shells', 'Дробь для дробовика', 'shells'),
    ('arrows', 'Стрелы / арбалетные болты', 'arrows'),
    ('rockets', 'Ракета', 'rockets'),
    ('pellets', 'Шарики для пневматики', 'pellets'),
]

def compatible(raw, kind):
    raw = raw.casefold()
    if re.match(r'^все(?:\s|,)', raw):
        return kind != 'pellets' and not (kind == 'shells' and 'кроме дроби' in raw) and not (kind == 'rockets' and 'кроме гранат и ракет' in raw)
    return bool(re.search(dict(bullets=r'пул', slugs=r'жакан', shells=r'дроб', arrows=r'стрел', rockets=r'ракет', pellets=r'шарик')[kind], raw))

def build(rows):
    result, identities = [], set()
    source_rows = [row for row in rows if row['tab'] in ('ammo', 'ammo-77')]
    if len(source_rows) != 27:
        raise ValueError('Ammo source changed; review all rows before updating the catalog')
    for row in source_rows:
        cells = row['cells']
        if len(cells) != 4:
            raise ValueError('Unexpected ammo row: ' + repr(cells))
        name, a, b, raw_price = cells
        compatibility, description = (a, b) if row['tab'] == 'ammo' else (b, a)
        key = row['tab'] + ':' + unicodedata.normalize('NFKC', name).casefold()
        if key in identities:
            raise ValueError('Duplicate ammo source identity: ' + name)
        identities.add(key)
        for caliber, label, kind in TYPES:
            if not compatible(compatibility, kind):
                continue
            # Core p344: ten rounds per pack, rockets individually. Source-specific
            # one/50/100-round offers override that default. 2070s smart ammo has
            # a separate explicitly stated rocket price.
            price_text = raw_price
            if row['tab'] == 'ammo-77' and kind == 'rockets':
                price_text = next(line for line in raw_price.splitlines() if 'за 1 ' in line)
            price = re.match(r'\s*(\d+)\s*[eе]b', price_text, re.I)
            if not price:
                raise ValueError('Unrecognized ammo price: ' + price_text)
            amount = int(price.group(1))
            explicit_size = re.search(r'за\s*(\d+)\s*(?:шт|штук)', price_text, re.I)
            count = 1 if kind == 'rockets' else int(explicit_size.group(1)) if explicit_size else 10
            identity = key + ':' + caliber
            item_id = 'ammo-' + sha256(identity.encode('utf-8')).hexdigest()[:16]
            notes = (description + '\n\nСовместимость в источнике: ' + compatibility +
                     '\nЦена в источнике: ' + raw_price +
                     f'\nОдна позиция инвентаря = {count} шт.; цена {amount} eb за эту упаковку.' +
                     '\nКалибр: ' + label +
                     '\nКоличество означает число упаковок. Перезарядка, расход запасов и специальные эффекты учитываются вручную.')
            if row['tab'] == 'ammo-77':
                notes += '\nВариант 2070-х; проверяйте совместимость с оружием этого периода.'
            result.append(dict(id=item_id, catalogId=item_id, sourceKey=identity, sourceUrl='https://alec-leon.github.io/data-pool/equipment/weapons/#' + row['tab'], section='ammunition', name=f'{name} — {label} ({count} шт.)', category='Ammunition', quantity=1, costEb=amount, priceLabel=f'{amount} eb / {count} шт.', notes=notes))
    if len({item['id'] for item in result}) != len(result):
        raise ValueError('Duplicate ammo ID')
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=SOURCE)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = args.source.read_text(encoding='utf-8')
    tables = Tables(); tables.feed(raw)
    items = build(tables.rows)
    output = ('// Generated by scripts/import-ammunition.py; package prices and full source effects retained.\n'
              '// Source SHA-256: ' + sha256(raw.encode('utf-8')).hexdigest() + '\n'
              'import type { CatalogGearItem } from "./datapoolCatalog";\n\n'
              'export const AMMUNITION_CATALOG: CatalogGearItem[] = ' + json.dumps(items, ensure_ascii=False, indent=2) + ';\n')
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != output:
            raise SystemExit('Ammunition catalog differs; run python scripts/import-ammunition.py')
    else:
        OUTPUT.write_text(output, encoding='utf-8')
    print(json.dumps(dict(offers=len(items), sourceRows=27, calibers=len(TYPES))))

if __name__ == '__main__':
    main()
