"""Import vehicle models from a saved Data Pool garage page.

Save https://alec-leon.github.io/data-pool/workshop/garage/ to
audit/source/garage.html, then run this script. --check verifies the output.
Only source-backed vehicle models are offered; user-owned records are untouched.
"""
import argparse
from collections import Counter
from hashlib import sha256
from html import unescape
import json
from pathlib import Path
import re
from datapool_tables import Tables, clean

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/data/vehicleCatalog.ts'
MARKER = 'export const VEHICLE_CATALOG: CatalogVehicleItem[] = '
SOURCE_URL = 'https://alec-leon.github.io/data-pool/workshop/garage/'
CATEGORIES = {'type-ground': ('Ground', 'Наземный транспорт', 'Ground vehicles'), 'type-sea': ('Sea', 'Водный транспорт', 'Watercraft'), 'type-air': ('Air', 'Воздушный транспорт', 'Aircraft')}

def normalize(value):
    return re.sub(r'[^a-zа-яё0-9]', '', value.lower().replace('ё','е'))

def previous_items():
    if OUTPUT.exists():
        return json.JSONDecoder().raw_decode(OUTPUT.read_text(encoding='utf-8').split(MARKER,1)[1])[0]
    text = (ROOT / 'src/data/datapoolVehicles.ts').read_text(encoding='utf-8')
    items = []
    for name in ('GROUND_VEHICLES','SEA_VEHICLES','AIR_VEHICLES','BICYCLES'):
        items.extend(json.JSONDecoder().raw_decode(text.split('export const DATAPOOL_'+name+': CatalogVehicleItem[] = ',1)[1])[0])
    return items

def build(rows, html, previous):
    old = {normalize(item['name']): item for item in previous}
    for alias,item_id in [('Колеса Янга Рикша','veh-ground-25'),('AV-4 Универ-ный Аэродайн','veh-air-3')]:
        old[normalize(alias)] = next(item for item in previous if item['id'] == item_id)
    items = []
    for row in rows:
        if row['tab'] not in CATEGORIES:
            continue
        columns = dict(zip((normalize(header) for header in row['headers']),row['cells']))
        name = ' '.join(columns['транспорт'].split())
        base = old.get(normalize(name))
        if not base:
            raise ValueError('Missing preserved vehicle identity: '+name)
        category,label,en_label = CATEGORIES[row['tab']]
        raw_price = columns['цена']
        amount = re.match(r'\s*(\d[\d,\s]*)',raw_price)
        if not amount:
            raise ValueError('Unknown price: '+name)
        seats = columns['мест']
        sdp = int(columns['пзт'])
        if sdp < 1:
            raise ValueError('Invalid SDP: '+name)
        rank = columns.get('рангкочевника','')
        items.append(dict(id=base['id'],catalogId=base['id'],name=name,nameEn=base.get('nameEn',name),category=category,typeLabelRu=columns.get('тип') or label,typeLabelEn=base.get('typeLabelEn',en_label),sdpMax=sdp,seats=int(seats) if seats.isdigit() else seats,speedCombat=columns['скоростьбой'],speedNarrative=columns['скоростьнарратив'],costEb=int(re.sub(r'\D','',amount[1])),priceLabel=raw_price,descriptionRu=columns['описание'],descriptionEn='',nomadRankReq=int(rank) if rank.isdigit() else 0,nomadRankLabel=rank,sourceUrl=SOURCE_URL+'#'+row['tab']))
    start = html.index('id="wheels"')
    end = html.index('<div class="tab-buttons">',start)
    bicycle_html = html[start:end].split('>',1)[1]
    text = re.sub(r'</(?:p|h[1-6]|tr)>|<br\s*/?>','\n',bicycle_html)
    description = clean(unescape(re.sub(r'<[^>]+>',' ',text)))
    if '100eb' not in description or '15' not in description:
        raise ValueError('Bicycle base rules changed; review the source')
    bike = next(item for item in previous if item['id'] == 'veh-bike-1')
    items.append(dict(id=bike['id'],catalogId=bike['id'],name='Велосипед',nameEn='Bicycle',category='Bicycle',typeLabelRu='Велосипед (Крути свои колеса DLC)',typeLabelEn='Bicycle (Wheels DLC)',sdpMax=15,seats=1,speedCombat='ТЕЛ <4: 8 СКО; ТЕЛ 4–7: 10 СКО; ТЕЛ 8+: 15 СКО',speedNarrative='ТЕЛ <4: 19 км/ч; ТЕЛ 4–7: 32 км/ч; ТЕЛ 8+: 48 км/ч',costEb=100,priceLabel='100 eb (Премиум)',descriptionRu=description,descriptionEn='',sourceUrl=SOURCE_URL+'#wheels'))
    expected = {item['id'] for item in previous if item['category'] != 'Bicycle'} | {'veh-bike-1'}
    if {item['id'] for item in items} != expected or len({item['id'] for item in items}) != len(items):
        raise ValueError('Missing or duplicate vehicle identity')
    return items

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--source',type=Path,default=ROOT / 'audit/source/garage.html')
    args = parser.parse_args()
    raw = args.source.read_bytes(); html = raw.decode('utf-8')
    tables = Tables(); tables.feed(html)
    items = build(tables.rows,html,previous_items())
    output = '// Generated by scripts/import-vehicles.py from saved public Data Pool garage tables.\n// Source SHA-256: '+sha256(raw).hexdigest()+'\nimport type { CatalogVehicleItem } from "./datapoolVehicles";\n\n'+MARKER+json.dumps(items,ensure_ascii=False,indent=2)+';\n'
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != output:
            raise SystemExit('Vehicle catalogue differs; regenerate it')
    else:
        OUTPUT.write_text(output,encoding='utf-8')
    print(json.dumps({'vehicles':len(items),'categories':dict(Counter(item['category'] for item in items))},ensure_ascii=False))

if __name__ == '__main__':
    main()
